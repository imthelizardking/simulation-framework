function filepath = generateScenarioRunner(params)
    % Writes a real, standalone runner script (into generated/) from
    % `params`, mirroring the hand-written runner_*.m scripts this
    % framework already has - not a parameterized simulation function
    % that hides what it does, but literal .m source text you can open,
    % read, and edit afterward exactly like any other runner. Returns the
    % path to the file it wrote (does not run it - see ScenarioBuilderApp,
    % which calls this then run()s the result).
    %
    % params (struct):
    %   MunitionKey  - one of munitionCatalog's keys (see below)
    %   FiringMode   - 'Direct' or 'Indirect'
    %   LauncherPos  - 3x1, Z-Up (downrange, crossrange, altitude)
    %   Direct mode:
    %     ElevationMil, AzimuthMil - scalars, mils
    %     MuzzleVelocity - m/s; overrides round.Charge.MuzzleVelocity
    %   Indirect mode:
    %     TargetPos - 3x1, Z-Up
    %     Branch    - 'Low' or 'High' (FireControlComputer branch)
    %
    % Phase-1 scope: unguided direct/indirect-fire munitions only (no
    % sensors/guidance/controller) - see the munition catalog below. All
    % five current presets use the DynamicsMPMM/AeroMPMM pair, so 'FDR' is
    % the correct sim.Frame for every one of them; this generator does not
    % (yet) need to branch on frame per munition.
    catalog = munitionCatalog();
    if ~isfield(catalog, params.MunitionKey)
        error('generateScenarioRunner:UnknownMunition', ...
            'Unknown MunitionKey "%s" - see munitionCatalog().', params.MunitionKey);
    end
    entry = catalog.(params.MunitionKey);

    here = fileparts(mfilename('fullpath'));
    out_dir = fullfile(here, 'generated');
    if ~isfolder(out_dir)
        mkdir(out_dir);
    end
    timestamp = datestr(now, 'yyyymmdd_HHMMSS'); %#ok<TNOW1,DATST> - fine for a unique filename, no need for datetime's extra ceremony here
    switch params.FiringMode
        case 'Direct'
            fname = sprintf('runner_generated_%s_direct_%s.m', params.MunitionKey, timestamp);
        case 'Indirect'
            fname = sprintf('runner_generated_%s_indirect_%s.m', params.MunitionKey, timestamp);
        otherwise
            error('generateScenarioRunner:UnknownFiringMode', ...
                'FiringMode must be ''Direct'' or ''Indirect'', got "%s".', params.FiringMode);
    end
    filepath = fullfile(out_dir, fname);

    lp = params.LauncherPos;
    lines = {};
    lines{end+1} = sprintf('%%%% Auto-generated Scenario: %s - %s Fire', entry.Label, params.FiringMode);
    lines{end+1} = sprintf('%% Generated by ScenarioBuilderApp on %s - a real, standalone script,', datestr(now, 'yyyy-mm-dd HH:MM:SS')); %#ok<TNOW1,DATST>
    lines{end+1} = '%% mirroring the hand-written runner_*.m scripts in this framework. Edit';
    lines{end+1} = '%% freely - regenerating from the GUI will not touch this file.';
    lines{end+1} = 'clear; clc; clf;';
    lines{end+1} = '';
    lines{end+1} = '%% 1. Setup Atmosphere';
    lines{end+1} = 'env = Atmosphere();';
    lines{end+1} = sprintf('launcher_pos = [%.3f; %.3f; %.3f];', lp(1), lp(2), lp(3));
    lines{end+1} = '';
    lines{end+1} = '%% 2. Instantiate Vehicle';
    lines{end+1} = sprintf('round = %s;', entry.FactoryCall);
    if strcmp(params.FiringMode, 'Direct')
        lines{end+1} = sprintf(['v0 = %.3f; %% muzzle velocity, from Scenario Builder ' ...
            '(round.Charge.MuzzleVelocity is this charge''s own default - edit here to try another)'], ...
            params.MuzzleVelocity);
    else
        lines{end+1} = 'v0 = round.Charge.MuzzleVelocity;';
    end
    lines{end+1} = '';

    switch params.FiringMode
        case 'Direct'
            lines{end+1} = '%% 3. Initial Launch State (direct fire - fixed elevation/azimuth, no solve)';
            lines{end+1} = sprintf('elevation = FireControlComputer.mil2rad(%.2f);', params.ElevationMil);
            lines{end+1} = sprintf('azimuth   = FireControlComputer.mil2rad(%.2f);', params.AzimuthMil);
            lines{end+1} = 'round.Dynamics.InitialState = round.buildLaunchState(launcher_pos, v0, elevation, azimuth);';
            lines{end+1} = '';
            lines{end+1} = '%% 4. Assemble Simulation & Execute';
            lines{end+1} = 'sim = Simulation(round, [], env, [0 60], 0.001);';
            lines{end+1} = 'sim.Frame = ''FDR'';';
            lines{end+1} = '';
            lines{end+1} = sprintf('fprintf(''Firing %s (direct fire) at %%.1f mils elevation, v0 = %%.0f m/s...\\n'', %.2f, v0);', ...
                entry.Label, params.ElevationMil);
            lines{end+1} = 'tic;';
            lines{end+1} = 'telemetry = sim.run();';
            lines{end+1} = 'fprintf(''Sim finished in %.2f seconds (%.2f s simulated).\n'', toc, telemetry.time(end));';
            lines{end+1} = '';
            lines{end+1} = '%% 5. Post-Flight Analysis';
            lines{end+1} = '[apogee, apogee_idx] = max(CoordinateFrame.altitudeColumn(telemetry.pos(:,2), telemetry.Frame));';
            lines{end+1} = 'final_pos     = telemetry.pos(end, :)'';';
            lines{end+1} = 'downrange     = final_pos(1);';
            lines{end+1} = 'deflection    = final_pos(3);';
            lines{end+1} = 'impact_range  = hypot(downrange, deflection);';
            lines{end+1} = '';
            lines{end+1} = 'fprintf(''Termination Reason : %s\n'', sim.TerminationReason);';
            lines{end+1} = 'fprintf(''Apogee              : %.1f m at t=%.2f s\n'', apogee, telemetry.time(apogee_idx));';
            lines{end+1} = 'fprintf(''Downrange           : %.1f m\n'', downrange);';
            lines{end+1} = 'fprintf(''Deflection          : %.1f m\n'', deflection);';
            lines{end+1} = 'fprintf(''Impact Range        : %.1f m\n'', impact_range);';
            lines{end+1} = 'fprintf(''Time of Flight      : %.2f s\n'', telemetry.time(end));';
            lines{end+1} = '';
            lines{end+1} = sprintf('plotTrajectoryProfile(telemetry, [], ''%s Direct Fire'');', entry.Label);

        case 'Indirect'
            tp = params.TargetPos;
            lines{end+1} = sprintf('%%%% 3. Target (static point, Z-Up: downrange/crossrange/altitude)');
            lines{end+1} = sprintf('target = TargetStatic([%.3f; %.3f; %.3f]);', tp(1), tp(2), tp(3));
            lines{end+1} = '';
            lines{end+1} = '%% 4. Fire Control Computer (solves Quadrant Elevation & Azimuth)';
            lines{end+1} = 'fcc = FireControlComputer(env.Gravity, ''Z-Up'');';
            lines{end+1} = 'fprintf(''Running Fire Control numerical shooting solver...\n'');';
            lines{end+1} = sprintf('sol = fcc.solveNumericalShooting(round, launcher_pos, v0, target.getTargetBus(), env, ''%s'', 0.005, ''FDR'');', params.Branch);
            lines{end+1} = '';
            lines{end+1} = 'if ~sol.IsValid';
            lines{end+1} = '    error(''Target is out of range or solution failed to converge!'');';
            lines{end+1} = 'end';
            lines{end+1} = 'fprintf(''Quadrant Elevation (QE) : %.1f mils\n'', sol.Elevation);';
            lines{end+1} = 'fprintf(''Azimuth                 : %.1f mils\n'', sol.Azimuth);';
            lines{end+1} = 'fprintf(''Predicted Flight Time   : %.2f s\n'', sol.TimeOfFlight);';
            lines{end+1} = '';
            lines{end+1} = '%% 5. Apply Solved Initial State';
            lines{end+1} = ['round.Dynamics.InitialState = round.buildLaunchState(launcher_pos, v0, ' ...
                'FireControlComputer.mil2rad(sol.Elevation), FireControlComputer.mil2rad(sol.Azimuth));'];
            lines{end+1} = '';
            lines{end+1} = '%% 6. Assemble Simulation & Execute';
            lines{end+1} = 'sim = Simulation(round, target, env, [0, sol.TimeOfFlight * 1.3], 0.005);';
            lines{end+1} = 'sim.Frame = ''FDR'';';
            lines{end+1} = '';
            lines{end+1} = 'fprintf(''Starting trajectory integration...\n'');';
            lines{end+1} = 'tic;';
            lines{end+1} = 'telemetry = sim.run();';
            lines{end+1} = 'fprintf(''Sim finished in %.2f seconds (%.2f s simulated).\n'', toc, telemetry.time(end));';
            lines{end+1} = '';
            lines{end+1} = '%% 7. Post-Flight Analysis';
            lines{end+1} = 'final_pos     = telemetry.pos(end, :)'';';
            lines{end+1} = 'final_tgt     = telemetry.target_pos(end, :)'';';
            lines{end+1} = 'downrange     = final_pos(1);';
            lines{end+1} = 'deflection    = final_pos(3);';
            lines{end+1} = 'total_range   = hypot(downrange, deflection);';
            lines{end+1} = 'miss_dist     = norm(final_pos([1 3]) - final_tgt([1 3]));';
            lines{end+1} = '[apogee, apogee_idx] = max(CoordinateFrame.altitudeColumn(telemetry.pos(:,2), telemetry.Frame));';
            lines{end+1} = '';
            lines{end+1} = 'fprintf(''Termination Reason   : %s\n'', sim.TerminationReason);';
            lines{end+1} = 'fprintf(''Apogee               : %.1f m at t=%.2f s\n'', apogee, telemetry.time(apogee_idx));';
            lines{end+1} = 'fprintf(''Downrange            : %.1f m\n'', downrange);';
            lines{end+1} = 'fprintf(''Deflection           : %.1f m\n'', deflection);';
            lines{end+1} = 'fprintf(''Total Range          : %.1f m\n'', total_range);';
            lines{end+1} = 'fprintf(''Impact Miss Distance : %.2f m\n'', miss_dist);';
            lines{end+1} = 'fprintf(''Time of Flight       : %.2f s\n'', telemetry.time(end));';
            lines{end+1} = '';
            lines{end+1} = sprintf('plotTrajectoryProfile(telemetry, final_tgt, ''%s Indirect Fire'');', entry.Label);
    end

    fid = fopen(filepath, 'w');
    if fid < 0
        error('generateScenarioRunner:WriteFailed', 'Could not open %s for writing.', filepath);
    end
    cleanupObj = onCleanup(@() fclose(fid)); %#ok<NASGU>
    for i = 1:numel(lines)
        fprintf(fid, '%s\n', lines{i});
    end
end
